def match_trigger_group(text: str) -> str | None:
    """
    Определяет, к какой группе триггеров относится текст: "chakry",
    "sposobnosti", "poslanie", или None, если ничего не совпало.
    Порядок проверки важен — более специфичные группы (чакры, способности)
    проверяются раньше общей группы "послание".
    """
    if not text:
        return None
    lowered = text.lower()
    # Порядок важен: сначала узкие темы, «послание» — в самом конце
    if any(k in lowered for k in TRIGGER_KEYWORDS_SPINA):
        return "spina"
    if any(k in lowered for k in TRIGGER_KEYWORDS_CHAKRY):
        return "chakry"
    if any(k in lowered for k in TRIGGER_KEYWORDS_MATRICA):
        return "matrica"
    if any(k in lowered for k in TRIGGER_KEYWORDS_SPOSOBNOSTI):
        return "sposobnosti"
    if any(k in lowered for k in TRIGGER_KEYWORDS_KURS):
        return "kurs"
    if any(k in lowered for k in TRIGGER_KEYWORDS_SESSIA):
        return "sessia"
    if any(k in lowered for k in TRIGGER_KEYWORDS_OTZYVY):
        return "otzyvy"
    if any(k in lowered for k in TRIGGER_KEYWORDS_POSLANIE):
        return "poslanie"
    return None


def text_matches_trigger(text: str) -> bool:
    """Оставлено для обратной совместимости — True, если сработала любая группа."""
    return match_trigger_group(text) is not None


